from datetime import datetime, UTC
from pathlib import Path

import pandas as pd
import pytest

from tslab.lab.analysis.numbers import (
    format_number,
    number_key,
    NumberKind,
    numbers_frame,
    write_numbers,
)
from tslab.lab.analysis.output import AnalysisOutput


def test_number_key() -> None:
    assert number_key(parts=['cls', 'TS2Vec_v2', 'acc 1.0']) == 'cls-TS2Vec-v2-acc-10'
    assert number_key(parts=[r'$\ell_\infty$', 'robust']) == 'Linf-robust'
    assert number_key(parts=[r'$\ell_2$', 'x']) == 'L2-x'
    assert number_key(parts=['a', '', 'b']) == 'a-b'


@pytest.mark.parametrize(
    ('value', 'kind', 'text'),
    [
        (0.12345, NumberKind.SCORE, r'\ensuremath{0.123}'),
        (-0.5, NumberKind.SCORE, r'\ensuremath{-0.500}'),
        (123.456, NumberKind.SIG4, r'\ensuremath{123.5}'),
        (0.456, NumberKind.RHO, r'\ensuremath{0.46}'),
        (1.234e-5, NumberKind.P, r'\ensuremath{1.2\times10^{-5}}'),
        (0.0, NumberKind.P, r'\ensuremath{<10^{-300}}'),
        (float('nan'), NumberKind.P, '--'),
        (12.0, NumberKind.COUNT, r'\ensuremath{12}'),
        ('TS2Vec', NumberKind.TEXT, 'TS2Vec'),
    ],
)
def test_format_number(value: float | str, kind: NumberKind, text: str) -> None:
    assert format_number(value=value, kind=kind) == text


def test_format_number_type_errors() -> None:
    with pytest.raises(TypeError, match='score'):
        format_number(value='x', kind=NumberKind.SCORE)
    with pytest.raises(TypeError, match='text'):
        format_number(value=1.0, kind=NumberKind.TEXT)


def two_numbers() -> pd.DataFrame:
    return numbers_frame(records=[('a-b', 0.5, NumberKind.SCORE), ('n', 3, NumberKind.COUNT)])


def test_numbers_frame_columns() -> None:
    frame = numbers_frame(records=[('best', 'TS2Vec', NumberKind.TEXT), ('n', 3, NumberKind.COUNT)])
    assert list(frame.columns) == ['key', 'value', 'raw']
    assert frame['value'].tolist() == ['TS2Vec', r'\ensuremath{3}']
    assert pd.isna(frame['raw'].iloc[0])
    assert frame['raw'].iloc[1] == 3.0


def test_write_numbers_exact_tex(tmp_path: Path) -> None:
    tex, csv = write_numbers(
        numbers=two_numbers(),
        output=AnalysisOutput(root=tmp_path),
        source='analysis.ipynb',
        now=datetime(2026, 11, 3, tzinfo=UTC),
        note='4 runs',
    )
    assert (tex, csv) == (tmp_path / 'results_numbers.tex', tmp_path / 'results_numbers.csv')
    assert tex.read_text(encoding='utf-8') == (
        '% Generated by analysis.ipynb on 2026-11-03. Do not edit by hand.\n'
        '% 4 runs\n'
        '\\newcommand{\\res}[1]{\\csname res@#1\\endcsname}\n'
        '\\expandafter\\def\\csname res@a-b\\endcsname{\\ensuremath{0.500}}\n'
        '\\expandafter\\def\\csname res@n\\endcsname{\\ensuremath{3}}\n'
    )
    assert pd.read_csv(csv)['key'].tolist() == ['a-b', 'n']


def test_write_numbers_without_note_has_no_note_line(tmp_path: Path) -> None:
    tex, _csv = write_numbers(
        numbers=two_numbers(),
        output=AnalysisOutput(root=tmp_path),
        source='s',
        now=datetime(2026, 11, 3, tzinfo=UTC),
    )
    assert tex.read_text(encoding='utf-8').splitlines()[1].startswith('\\newcommand')


def test_write_numbers_rejects_duplicates_and_bad_stem(tmp_path: Path) -> None:
    duplicated = numbers_frame(records=[('k', 1.0, NumberKind.SCORE), ('k', 2.0, NumberKind.SCORE)])
    output = AnalysisOutput(root=tmp_path)
    now = datetime(2026, 11, 3, tzinfo=UTC)
    with pytest.raises(ValueError, match="'k'"):
        write_numbers(numbers=duplicated, output=output, source='s', now=now)
    with pytest.raises(ValueError, match='Bad Stem'):
        write_numbers(numbers=two_numbers(), output=output, source='s', now=now, stem='Bad Stem')
    assert list(tmp_path.iterdir()) == []


@pytest.mark.parametrize('part', ['top-5%', 'a{b', 'a}b', 'a#b', 'a&b', r'a\b', 'a~b', 'a^b'])
def test_number_key_rejects_tex_unsafe_characters(part: str) -> None:
    with pytest.raises(ValueError, match='TeX'):
        number_key(parts=['x', part])


def test_text_numbers_are_tex_escaped() -> None:
    assert format_number(value='patchtst_long', kind=NumberKind.TEXT) == r'patchtst\_long'
    assert format_number(value='100% & $5 #1', kind=NumberKind.TEXT) == r'100\% \& \$5 \#1'
    assert format_number(value='a{b}', kind=NumberKind.TEXT) == r'a\{b\}'
    assert format_number(value=r'a\b~c^d', kind=NumberKind.TEXT) == (
        r'a\textbackslash{}b\textasciitilde{}c\textasciicircum{}d'
    )
